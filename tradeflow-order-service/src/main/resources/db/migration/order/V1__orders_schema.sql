CREATE TABLE orders (
    id                 UUID          PRIMARY KEY,
    user_id            BIGINT        NOT NULL,
    client_order_id    VARCHAR(64),
    symbol             VARCHAR(20)   NOT NULL,
    side               VARCHAR(4)    NOT NULL,
    order_type         VARCHAR(10)   NOT NULL,
    quantity           BIGINT        NOT NULL CHECK (quantity > 0),
    limit_price        NUMERIC(19,4),
    reservation_price  NUMERIC(19,4) NOT NULL CHECK (reservation_price > 0),
    status             VARCHAR(20)   NOT NULL,
    reject_code        VARCHAR(50),
    status_reason      VARCHAR(500),
    filled_quantity    BIGINT        NOT NULL DEFAULT 0,
    average_fill_price NUMERIC(19,4),
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    version            BIGINT        NOT NULL DEFAULT 0,
    -- Idempotency key: one order per (user, clientOrderId). NULLs never collide.
    CONSTRAINT uk_orders_user_client_order UNIQUE (user_id, client_order_id),
    CONSTRAINT ck_orders_filled CHECK (filled_quantity >= 0 AND filled_quantity <= quantity)
);
CREATE INDEX idx_orders_user_created ON orders (user_id, created_at);
CREATE INDEX idx_orders_symbol_status ON orders (symbol, status);

CREATE TABLE trades (
    id           UUID          PRIMARY KEY,
    order_id     UUID          NOT NULL REFERENCES orders (id),
    user_id      BIGINT        NOT NULL,
    symbol       VARCHAR(20)   NOT NULL,
    side         VARCHAR(4)    NOT NULL,
    quantity     BIGINT        NOT NULL CHECK (quantity > 0),
    price        NUMERIC(19,4) NOT NULL CHECK (price > 0),
    gross_amount NUMERIC(19,4) NOT NULL CHECK (gross_amount > 0),
    executed_at  TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_trades_user_executed ON trades (user_id, executed_at);
CREATE INDEX idx_trades_order ON trades (order_id);

-- Audit trail of every status change; drives "why is my order in this state?".
CREATE TABLE order_status_history (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id    UUID         NOT NULL REFERENCES orders (id),
    from_status VARCHAR(20),
    to_status   VARCHAR(20)  NOT NULL,
    reason      VARCHAR(500),
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_order_status_history_order ON order_status_history (order_id);

-- Local copy of the latest simulated price per symbol, fed by prices.updated.
CREATE TABLE latest_prices (
    symbol VARCHAR(20)   PRIMARY KEY,
    price  NUMERIC(19,4) NOT NULL,
    tick   BIGINT        NOT NULL,
    as_of  TIMESTAMP WITH TIME ZONE NOT NULL
);
