-- Trading readiness: state per user, an append-only hash-chained audit log, practical exercises
-- verified from DEMO order events, reviews of repeated assessment failures, risk acknowledgements.

CREATE TABLE readiness_status (
    user_id                    BIGINT       PRIMARY KEY,
    state                      VARCHAR(30)  NOT NULL,
    state_reason               VARCHAR(60)  NOT NULL,
    policy_version             INTEGER      NOT NULL,
    cycle_started_at           TIMESTAMP WITH TIME ZONE,
    qualified_at               TIMESTAMP WITH TIME ZONE,
    qualified_policy_version   INTEGER,
    expires_at                 TIMESTAMP WITH TIME ZONE,
    remediation_modules        VARCHAR(500),
    remediation_since          TIMESTAMP WITH TIME ZONE,
    self_excluded_until        TIMESTAMP WITH TIME ZONE,
    updated_at                 TIMESTAMP WITH TIME ZONE NOT NULL,
    version                    BIGINT       NOT NULL DEFAULT 0
);

-- Append-only (see V4 for the PostgreSQL trigger). hash = SHA-256 over the previous hash and this
-- row's fields, so any edit or deletion breaks the chain and is detected by verification.
CREATE TABLE readiness_events (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT        NOT NULL,
    seq             INTEGER       NOT NULL,
    from_state      VARCHAR(30),
    to_state        VARCHAR(30)   NOT NULL,
    reason_code     VARCHAR(60)   NOT NULL,
    actor_type      VARCHAR(12)   NOT NULL,
    actor_id        BIGINT,
    policy_version  INTEGER       NOT NULL,
    detail          VARCHAR(1000),
    occurred_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    prev_hash       VARCHAR(64)   NOT NULL,
    hash            VARCHAR(64)   NOT NULL,
    CONSTRAINT uk_readiness_events_user_seq UNIQUE (user_id, seq)
);

CREATE TABLE risk_acknowledgements (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT        NOT NULL,
    policy_version  INTEGER       NOT NULL,
    text_version    INTEGER       NOT NULL,
    text_sha256     VARCHAR(64)   NOT NULL,
    typed_phrase    VARCHAR(100)  NOT NULL,
    accepted_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    client_ip       VARCHAR(64),
    user_agent      VARCHAR(255)
);
CREATE INDEX idx_risk_ack_user ON risk_acknowledgements (user_id, accepted_at);

CREATE TABLE exercise_progress (
    user_id       BIGINT        NOT NULL,
    slug          VARCHAR(60)   NOT NULL,
    started_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    completed_at  TIMESTAMP WITH TIME ZONE,
    evidence      VARCHAR(500),
    PRIMARY KEY (user_id, slug)
);

CREATE TABLE position_sizing_scenarios (
    id                     UUID          PRIMARY KEY,
    user_id                BIGINT        NOT NULL,
    symbol                 VARCHAR(20)   NOT NULL,
    account_value          NUMERIC(19,2) NOT NULL,
    risk_bps               INTEGER       NOT NULL,
    entry_price            NUMERIC(19,2) NOT NULL,
    stop_price             NUMERIC(19,2) NOT NULL,
    expected_quantity      BIGINT        NOT NULL,
    issued_at              TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at             TIMESTAMP WITH TIME ZONE NOT NULL,
    answered_correctly_at  TIMESTAMP WITH TIME ZONE,
    answer_attempts        INTEGER       NOT NULL DEFAULT 0
);
CREATE INDEX idx_sizing_user ON position_sizing_scenarios (user_id, issued_at);

-- DEMO orders observed from Kafka (evidence for exercises only). Events of different topics can
-- arrive in any order, so a row may first exist with only the fields one event carries.
CREATE TABLE observed_orders (
    order_id        UUID          PRIMARY KEY,
    user_id         BIGINT        NOT NULL,
    symbol          VARCHAR(20),
    side            VARCHAR(4),
    order_type      VARCHAR(10),
    quantity        BIGINT,
    observed_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    placed_at       TIMESTAMP WITH TIME ZONE,
    reserved_at     TIMESTAMP WITH TIME ZONE,
    cancelled_at    TIMESTAMP WITH TIME ZONE,
    cancel_reason   VARCHAR(200),
    filled_at       TIMESTAMP WITH TIME ZONE
);
CREATE INDEX idx_observed_orders_user ON observed_orders (user_id);

CREATE TABLE readiness_reviews (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                BIGINT        NOT NULL,
    reviewer_id            BIGINT        NOT NULL,
    reviewer_role          VARCHAR(20)   NOT NULL,
    decision               VARCHAR(30)   NOT NULL,
    notes                  VARCHAR(1000) NOT NULL,
    remediation_modules    VARCHAR(500),
    failed_attempts        INTEGER       NOT NULL,
    decided_at             TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_readiness_reviews_user ON readiness_reviews (user_id, decided_at);
