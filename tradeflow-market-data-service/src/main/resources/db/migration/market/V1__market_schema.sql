CREATE TABLE instruments (
    symbol      VARCHAR(20)   PRIMARY KEY,
    name        VARCHAR(120)  NOT NULL,
    sector      VARCHAR(60)   NOT NULL,
    asset_class VARCHAR(20)   NOT NULL,
    currency    VARCHAR(3)    NOT NULL,
    base_price  NUMERIC(19,4) NOT NULL CHECK (base_price > 0),
    volatility  NUMERIC(9,6)  NOT NULL CHECK (volatility >= 0),
    drift       NUMERIC(9,6)  NOT NULL
);

CREATE TABLE price_ticks (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    symbol VARCHAR(20)   NOT NULL REFERENCES instruments (symbol),
    tick   BIGINT        NOT NULL,
    price  NUMERIC(19,4) NOT NULL CHECK (price > 0),
    as_of  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_price_ticks_symbol_tick UNIQUE (symbol, tick)
);
CREATE INDEX idx_price_ticks_symbol_as_of ON price_ticks (symbol, as_of);

-- Single-row table holding the simulation clock; locked while a tick is generated.
CREATE TABLE simulation_state (
    id           INTEGER PRIMARY KEY,
    current_tick BIGINT  NOT NULL,
    updated_at   TIMESTAMP WITH TIME ZONE
);

CREATE TABLE watchlist_items (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id  BIGINT      NOT NULL,
    symbol   VARCHAR(20) NOT NULL REFERENCES instruments (symbol),
    added_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_watchlist_user_symbol UNIQUE (user_id, symbol)
);

CREATE TABLE price_alerts (
    id              UUID          PRIMARY KEY,
    user_id         BIGINT        NOT NULL,
    symbol          VARCHAR(20)   NOT NULL REFERENCES instruments (symbol),
    direction       VARCHAR(10)   NOT NULL,
    threshold       NUMERIC(19,4) NOT NULL CHECK (threshold > 0),
    status          VARCHAR(20)   NOT NULL,
    note            VARCHAR(200),
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    triggered_at    TIMESTAMP WITH TIME ZONE,
    triggered_price NUMERIC(19,4),
    version         BIGINT        NOT NULL DEFAULT 0
);
CREATE INDEX idx_price_alerts_symbol_status ON price_alerts (symbol, status);
CREATE INDEX idx_price_alerts_user ON price_alerts (user_id);
