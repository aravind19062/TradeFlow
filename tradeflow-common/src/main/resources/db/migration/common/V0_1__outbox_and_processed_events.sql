-- Shared by every service (each service has its own database).
-- Portable SQL: runs unchanged on PostgreSQL 16 and H2 2.x (MODE=PostgreSQL).

CREATE TABLE outbox_events (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id     UUID          NOT NULL UNIQUE,
    topic        VARCHAR(200)  NOT NULL,
    message_key  VARCHAR(200)  NOT NULL,
    payload      VARCHAR(8000) NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    published_at TIMESTAMP WITH TIME ZONE,
    attempts     INTEGER       NOT NULL DEFAULT 0,
    last_error   VARCHAR(1000)
);

CREATE INDEX idx_outbox_events_unpublished ON outbox_events (published_at, id);

CREATE TABLE processed_events (
    event_id     UUID         PRIMARY KEY,
    consumer     VARCHAR(100) NOT NULL,
    processed_at TIMESTAMP WITH TIME ZONE NOT NULL
);
