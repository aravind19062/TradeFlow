-- Invariants are enforced twice: in the domain model and by CHECK constraints,
-- so a bug cannot persist negative cash or over-reserved positions.
CREATE TABLE accounts (
    user_id       BIGINT        PRIMARY KEY,
    cash_balance  NUMERIC(19,4) NOT NULL,
    reserved_cash NUMERIC(19,4) NOT NULL DEFAULT 0,
    net_deposits  NUMERIC(19,4) NOT NULL,
    realized_pnl  NUMERIC(19,4) NOT NULL DEFAULT 0,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    version       BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT ck_accounts_cash CHECK (cash_balance >= 0 AND reserved_cash >= 0 AND reserved_cash <= cash_balance)
);

CREATE TABLE holdings (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           BIGINT        NOT NULL REFERENCES accounts (user_id),
    symbol            VARCHAR(20)   NOT NULL,
    quantity          BIGINT        NOT NULL DEFAULT 0,
    reserved_quantity BIGINT        NOT NULL DEFAULT 0,
    average_cost      NUMERIC(19,4) NOT NULL DEFAULT 0,
    realized_pnl      NUMERIC(19,4) NOT NULL DEFAULT 0,
    updated_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    version           BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT uk_holdings_user_symbol UNIQUE (user_id, symbol),
    CONSTRAINT ck_holdings_quantity CHECK (quantity >= 0 AND reserved_quantity >= 0 AND reserved_quantity <= quantity)
);

-- One reservation per order: cash for BUY, shares for SELL.
CREATE TABLE reservations (
    order_id    UUID          PRIMARY KEY,
    user_id     BIGINT        NOT NULL REFERENCES accounts (user_id),
    symbol      VARCHAR(20)   NOT NULL,
    side        VARCHAR(4)    NOT NULL,
    quantity    BIGINT        NOT NULL CHECK (quantity > 0),
    cash_amount NUMERIC(19,4) NOT NULL CHECK (cash_amount >= 0),
    status      VARCHAR(20)   NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    resolved_at TIMESTAMP WITH TIME ZONE,
    version     BIGINT        NOT NULL DEFAULT 0
);
CREATE INDEX idx_reservations_user_status ON reservations (user_id, status);
CREATE INDEX idx_reservations_status_created ON reservations (status, created_at);

-- Append-only cash/position journal. trade_id is UNIQUE: a trade can never be booked twice.
CREATE TABLE ledger_entries (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id            BIGINT        NOT NULL REFERENCES accounts (user_id),
    entry_type         VARCHAR(20)   NOT NULL,
    symbol             VARCHAR(20),
    quantity           BIGINT,
    price              NUMERIC(19,4),
    cash_delta         NUMERIC(19,4) NOT NULL,
    cash_balance_after NUMERIC(19,4) NOT NULL,
    realized_pnl       NUMERIC(19,4),
    trade_id           UUID UNIQUE,
    order_id           UUID,
    occurred_at        TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_ledger_user_occurred ON ledger_entries (user_id, occurred_at, id);
