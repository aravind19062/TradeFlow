-- LIVE trading (real money). Physically separate database; nothing here refers to the simulated engine.

CREATE TABLE broker_connections (
    id                  UUID         PRIMARY KEY,
    user_id             BIGINT       NOT NULL,
    broker_code         VARCHAR(30)  NOT NULL,
    status              VARCHAR(20)  NOT NULL,
    broker_account_ref  VARCHAR(100),
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    connected_at        TIMESTAMP WITH TIME ZONE,
    expires_at          TIMESTAMP WITH TIME ZONE,
    disconnected_at     TIMESTAMP WITH TIME ZONE,
    version             BIGINT       NOT NULL DEFAULT 0
);
CREATE INDEX idx_broker_connections_user ON broker_connections (user_id, status);

-- Broker access/refresh tokens: AES-256-GCM ciphertext bound to the connection id. Never returned by
-- any API and never logged.
CREATE TABLE broker_credentials (
    connection_id       UUID          PRIMARY KEY REFERENCES broker_connections (id),
    access_token_ct     VARCHAR(4000) NOT NULL,
    refresh_token_ct    VARCHAR(4000),
    key_id              VARCHAR(60)   NOT NULL,
    expires_at          TIMESTAMP WITH TIME ZONE,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL
);

-- OAuth-style authorisation round trip: one-time state (CSRF) and PKCE verifier (encrypted).
CREATE TABLE oauth_states (
    state_hash          VARCHAR(64)   PRIMARY KEY,
    user_id             BIGINT        NOT NULL,
    broker_code         VARCHAR(30)   NOT NULL,
    connection_id       UUID          NOT NULL,
    verifier_ct         VARCHAR(1000) NOT NULL,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    consumed_at         TIMESTAMP WITH TIME ZONE
);

CREATE TABLE order_confirmations (
    id                  UUID          PRIMARY KEY,
    user_id             BIGINT        NOT NULL,
    params_sha256       VARCHAR(64)   NOT NULL,
    order_value         NUMERIC(19,2) NOT NULL,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    consumed_at         TIMESTAMP WITH TIME ZONE
);

CREATE TABLE live_orders (
    id                  VARCHAR(40)   PRIMARY KEY,
    user_id             BIGINT        NOT NULL,
    connection_id       UUID          NOT NULL REFERENCES broker_connections (id),
    client_order_id     VARCHAR(64)   NOT NULL,
    broker_order_id     VARCHAR(100),
    exchange            VARCHAR(10)   NOT NULL,
    symbol              VARCHAR(30)   NOT NULL,
    side                VARCHAR(4)    NOT NULL,
    order_type          VARCHAR(12)   NOT NULL,
    quantity            BIGINT        NOT NULL CHECK (quantity > 0),
    limit_price         NUMERIC(19,2),
    trigger_price       NUMERIC(19,2),
    order_value         NUMERIC(19,2) NOT NULL,
    status              VARCHAR(20)   NOT NULL,
    status_message      VARCHAR(500),
    filled_quantity     BIGINT        NOT NULL DEFAULT 0,
    average_price       NUMERIC(19,4),
    confirmation_id     UUID          NOT NULL,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    version             BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT uk_live_orders_client UNIQUE (user_id, client_order_id)
);
CREATE INDEX idx_live_orders_user ON live_orders (user_id, created_at);

-- Platform limits are ceilings; a user's row can only be stricter.
CREATE TABLE risk_limits (
    user_id              BIGINT        PRIMARY KEY,
    max_order_value      NUMERIC(19,2) NOT NULL,
    max_orders_per_day   INTEGER       NOT NULL,
    max_daily_turnover   NUMERIC(19,2) NOT NULL,
    updated_at           TIMESTAMP WITH TIME ZONE NOT NULL
);

-- scope GLOBAL (user_id 0) or USER.
CREATE TABLE kill_switches (
    scope       VARCHAR(10)   NOT NULL,
    user_id     BIGINT        NOT NULL,
    enabled     BOOLEAN       NOT NULL,
    reason      VARCHAR(500)  NOT NULL,
    actor_id    BIGINT        NOT NULL,
    changed_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (scope, user_id)
);

CREATE TABLE live_notifications (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT        NOT NULL,
    kind        VARCHAR(40)   NOT NULL,
    message     VARCHAR(1000) NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    read_at     TIMESTAMP WITH TIME ZONE
);
CREATE INDEX idx_live_notifications_user ON live_notifications (user_id, created_at);

-- Every live action, allowed or refused: append-only, hash-chained per user.
CREATE TABLE live_audit_log (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT        NOT NULL,
    seq          INTEGER       NOT NULL,
    action       VARCHAR(40)   NOT NULL,
    outcome      VARCHAR(20)   NOT NULL,
    detail       VARCHAR(1000),
    actor_id     BIGINT        NOT NULL,
    client_ip    VARCHAR(64),
    occurred_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    prev_hash    VARCHAR(64)   NOT NULL,
    hash         VARCHAR(64)   NOT NULL,
    CONSTRAINT uk_live_audit_user_seq UNIQUE (user_id, seq)
);
