-- Phase 2 security hardening: revocable sessions (rotating refresh tokens), TOTP MFA with
-- recovery codes, login MFA challenges and an append-only security event log.
-- Additive only. users.pan_number is no longer written or read by the application; it is
-- kept untouched until the migration in docs/PAN_MIGRATION.md is approved.

-- Bumped to invalidate every access and refresh token of a user (sign out everywhere,
-- MFA reset, MFA disabled). Access tokens carry it as the "tv" claim.
ALTER TABLE users ADD COLUMN token_version INTEGER NOT NULL DEFAULT 0;
-- Set by an administrator MFA reset; live-trading step-up is refused for 24 h afterwards.
ALTER TABLE users ADD COLUMN mfa_reset_at TIMESTAMP WITH TIME ZONE;

CREATE TABLE refresh_tokens (
    id                  UUID         PRIMARY KEY,
    user_id             BIGINT       NOT NULL REFERENCES users (id),
    family_id           UUID         NOT NULL,
    token_hash          VARCHAR(64)  NOT NULL UNIQUE,
    token_version       INTEGER      NOT NULL,
    amr                 VARCHAR(40)  NOT NULL,
    issued_at           TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    session_expires_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    used_at             TIMESTAMP WITH TIME ZONE,
    revoked_at          TIMESTAMP WITH TIME ZONE,
    revoke_reason       VARCHAR(60),
    client_ip           VARCHAR(64),
    user_agent          VARCHAR(255)
);
CREATE INDEX idx_refresh_tokens_family ON refresh_tokens (family_id);
CREATE INDEX idx_refresh_tokens_user ON refresh_tokens (user_id);

CREATE TABLE user_totp (
    user_id            BIGINT       PRIMARY KEY REFERENCES users (id),
    secret_ciphertext  VARCHAR(512) NOT NULL,
    status             VARCHAR(16)  NOT NULL,
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    enabled_at         TIMESTAMP WITH TIME ZONE,
    last_used_step     BIGINT       NOT NULL DEFAULT -1,
    version            BIGINT       NOT NULL DEFAULT 0
);

CREATE TABLE recovery_codes (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL REFERENCES users (id),
    code_hash   VARCHAR(100) NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    used_at     TIMESTAMP WITH TIME ZONE
);
CREATE INDEX idx_recovery_codes_user ON recovery_codes (user_id);

CREATE TABLE mfa_challenges (
    id           UUID        PRIMARY KEY,
    token_hash   VARCHAR(64) NOT NULL UNIQUE,
    user_id      BIGINT      NOT NULL REFERENCES users (id),
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    attempts     INTEGER     NOT NULL DEFAULT 0,
    consumed_at  TIMESTAMP WITH TIME ZONE
);

-- Append-only: the application only inserts. Users see their own events; admins see all.
CREATE TABLE security_events (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL,
    type        VARCHAR(40)  NOT NULL,
    actor_id    BIGINT,
    detail      VARCHAR(500),
    client_ip   VARCHAR(64),
    user_agent  VARCHAR(255),
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_security_events_user ON security_events (user_id, occurred_at);
